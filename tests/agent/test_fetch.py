def test_without_huggingface_hub_the_fallback_says_how_to_get_it(tmp_path, monkeypatch):
    import builtins  # pylint: disable=import-outside-toplevel
    real_import = builtins.__import__

    def no_hub(name, *args, **kwargs):
        if name == 'huggingface_hub':
            raise ImportError(name)
        return real_import(name, *args, **kwargs)
    monkeypatch.setattr(builtins, '__import__', no_hub)
    with pytest.raises(FetchError, match='huggingface_hub'):
        fetch_model(TAG, lambda line: None, popen=FakeOllama(pull=1), binary='ollama',
                    models_dir=tmp_path / 'models', models_fn=_up)


def test_progress_drops_the_cli_spinner(tmp_path):
    """Ollama redraws a spinner with ANSI codes even into a pipe (0.40.7, seen live)."""
    frame = '\x1b[?2026h\x1b[?25l\x1b[1Gpulling manifest {} \x1b[K\x1b[?25h\x1b[?2026l'
    out = (''.join(frame.format(c) for c in '⠙⠹⠸')
           + '\x1b[?2026h\x1b[?25l\x1b[1Gpulling 2f3a 40%\rpulling 2f3a 100% \x1b[K\n'
           + 'success \x1b[K\x1b[?25h\x1b[?2026l\n')

    class Spinning(FakeOllama):
        def __call__(self, cmd, **kwargs):
            process = super().__call__(cmd, **kwargs)
            if cmd[1] == 'pull':
                process.stdout = io.StringIO(out)
            return process
    lines = []
    _fetch(tmp_path, Spinning(), lines=lines)
    assert lines[:4] == ['pulling manifest', 'pulling 2f3a 40%', 'pulling 2f3a 100%',
                         'success']


def test_serving_lines_are_matched_whatever_the_spacing():
    assert serves_as_trained(SHOWN) and serves_as_trained(MODELFILE)
    assert serves_as_trained(SHOWN.replace('PARSER qwen3.5', 'parser   qwen3.5'))
    assert not serves_as_trained(SHOWN_PULLED)
    assert not serves_as_trained(SHOWN.replace('num_ctx 16384', 'num_ctx 4096'))


def test_list_marks_installed(tmp_path):
    folder = tmp_path / 'models' / 'qwen3.5-9b'
    folder.mkdir(parents=True)
    (folder / 'manifest.json').write_text(json.dumps(
        {'tag': 'qwen3.5-9b', 'base': 'b', 'schema_hash': 's', 'size': 5780090720}))
    found = available(models=['fs2d-assistant:qwen3.5-4b', 'qwen3.5:4b'],
                      models_dir=tmp_path / 'models')
    assert sorted(found) == ['qwen3.5-2b', 'qwen3.5-4b', 'qwen3.5-9b']
    assert {tag: row['installed'] for tag, row in found.items()} == {
        'qwen3.5-2b': False, 'qwen3.5-4b': True, 'qwen3.5-9b': False}
    assert found['qwen3.5-9b']['size'] == 5780090720 and found['qwen3.5-4b']['size'] is None
    assert found['qwen3.5-2b']['repo'] == 'mjvalder/fs2d-assistant-qwen3.5-2b'


