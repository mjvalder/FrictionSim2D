"""Deriving the form from the config models.

The forms are generated by introspecting the pydantic models rather than being
written out field by field, so that a field added to a config model appears in
the GUI without a GUI edit. That matters here because the config models are
under active development on another branch.

Introspection cannot know what a field *means*, so a small declarative override
table supplies labels, units, ordering and dependencies. Anything without an
override still renders; the coverage test reports it.
"""

