"""Interlayer-interaction vocabulary: styles, parameter files and validation.

The interaction BETWEEN the layers of a 2D stack can be the run's normal
Lennard-Jones (``lj``), LJ plus the Jiang-Park Gaussian (``lj_g``), or a
registered many-body style (``ilp``, ``kc``). This module holds the vocabulary
and the checks; emission lives in :mod:`frictionsim2d.potentials.manager`.

Must not import ``ase`` (``tests/repo/test_import_weight.py``): the CIF read in
:func:`check_interlayer_choice` is a deferred import.
"""
from pathlib import Path
from typing import Any, Dict, List, Optional, Set, Tuple

from ..core.utils.paths import get_material_path, get_potential_path

INTERLAYER_STYLES: Tuple[str, ...] = ('lj', 'lj_g', 'ilp', 'kc')

#: Jiang-Park Gaussian strength g (meV) by material, structure prefix stripped.
GAUSSIAN_G_MEV: Dict[str, float] = {
    'MoS2': 175.68, 'graphene': 94.87, 'C': 94.87, 'BP': 123.0, 'P': 123.0,
}

#: Cutoff (Angstrom) of ``ilp/tmd`` and ``kolmogorov/crespi/full``.
ILP_CUTOFF = 16.0
KC_FULL_CUTOFF = 16.0
#: LAMMPS ilp/kc ``tap_flag`` argument: 1 = taper the cutoff.
TAPER_FLAG = 1

EXAMPLES_POTENTIALS_DIR = Path(__file__).resolve().parents[2] / 'examples' / 'potentials'

_ILP_TMD = {'Mo', 'W', 'S', 'Se'}
_ILP_BNCH = {'B', 'N', 'C', 'H'}


def _strip_prefix(mat: str) -> str:
    """Drop the structure prefix (``h_``, ``t-``, ...) from a material name."""
    if len(mat) > 2 and mat[0] in 'htbp' and mat[1] in '_-':
        return mat[2:]
    return mat


def gaussian_g(mat: str, override: Optional[float]) -> Optional[float]:
    """Gaussian strength (meV) for ``mat``: the override, else the table, else None."""
    if override is not None:
        return float(override)
    return GAUSSIAN_G_MEV.get(_strip_prefix(mat))


def mixed_g(g1: float, g2: float) -> float:
    """Geometric-mean Gaussian strength for a heterostructure interface."""
    return (g1 * g2) ** 0.5


#: Fixed KC/z columns that turn the potential into a pure Gaussian.
_GAUSSIAN_KC_Z0 = 3.0
_GAUSSIAN_KC_DELTA = 1.0
_GAUSSIAN_KC_S = 1.0


def write_gaussian_kc_file(path: Path, pairs: Dict[Tuple[str, str], float],
                           sign: int) -> Path:
    """Write a ``kolmogorov/crespi/z`` file that is the Jiang-Park Gaussian.

    With lambda = A = C = C2 = C4 = 0 and delta = 1 the KC/z energy is
    ``2 C0 exp(-rho^2)``; ``C0 = sign * g / 2`` therefore gives ``sign * g
    exp(-rho^2)`` (meV). One line per ordered element pair; a pair given in
    one order only is written in both.

    Args:
        path: File to write.
        pairs: ``(el1, el2) -> g`` in meV.
        sign: ``+1`` (all-layer instance) or ``-1`` (same-layer cancellation).

    Raises:
        ValueError: If ``sign`` is not +1 or -1.
    """
    if sign not in (1, -1):
        raise ValueError(f"sign must be +1 or -1, got {sign!r}")
    ordered: Dict[Tuple[str, str], float] = {}
    for (el1, el2), g in pairs.items():
        ordered.setdefault((el1, el2), g)
    for (el1, el2), g in list(ordered.items()):
        ordered.setdefault((el2, el1), g)
    lines: List[str] = [
        "# Jiang-Park Gaussian V = g exp(-rho^2) as kolmogorov/crespi/z "
        "(generated by FrictionSim2D)",
        "# UNITS: metal (energies in meV)",
        f"# sign = {sign:+d}; C0 = sign * g / 2",
        "#  z0  C0  C2  C4  C  delta  lambda  A  S",
    ]
    for (el1, el2), g in ordered.items():
        c0 = f"{sign * float(g) / 2:.15g}"
        lines.append(f"{el1} {el2} {_GAUSSIAN_KC_Z0} {c0} 0.0 0.0 0.0 "
                     f"{_GAUSSIAN_KC_DELTA} 0.0 0.0 {_GAUSSIAN_KC_S}")
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding='utf-8')
    return path


def default_interlayer_file(style: str, elements: Set[str]) -> Optional[str]:
    """Bundled parameter-file name for ``style`` over ``elements``, or None."""
    elems = set(elements)
    if style == 'ilp':
        if elems <= _ILP_TMD:
            return 'TMD.ILP'
        if elems <= _ILP_BNCH:
            return 'BNCH.ILP'
    elif style == 'kc':
        if elems <= {'C'}:
            return 'CC.KC-full'
        if elems <= {'C', 'H'}:
            return 'CH.KC'
    return None


def ilp_substyle(elements: Set[str]) -> str:
    """LAMMPS ILP sub-style for ``elements``."""
    return 'ilp/tmd' if set(elements) <= _ILP_TMD else 'ilp/graphene/hbn'


#: Chalcogens whose two sub-layers ilp/tmd must see as different atom types.
CHALCOGENS = frozenset({'S', 'Se', 'Te'})

#: Components whose data comes from ``build_monolayer`` (``build_sheet`` /
#: ``build_flake_component``), the only place the split is applied to a data
#: file; the potential manager splits the same components' types. The hetero
#: components numbered after them (``sheet_1``, ``flake_2``, ...; see
#: :func:`splits_chalcogens`) are built from ``build_monolayer`` too.
_SPLIT_COMPONENTS = ('sheet', 'flake')


def splits_chalcogens(component: str) -> bool:
    """Whether ``component``'s chalcogen sub-layers get their own types under ilp/tmd.

    ``sheet`` and ``flake``, plus the hetero components numbered after them
    (``sheet_1``/``sheet_2`` from ``register_sheet_block``, ``flake_1``/
    ``flake_2`` of a hetero flake): every one of them is read from a
    ``build_monolayer`` file, which applies the same split.
    """
    if component in _SPLIT_COMPONENTS:
        return True
    base, _, index = component.rpartition('_')
    return base in _SPLIT_COMPONENTS and index.isdigit()


def chalcogen_split_elements(style: str, elements, pot_counts: Dict[str, int]) -> Set[str]:
    """Chalcogens to split into a top and a bottom sub-layer type.

    ilp/tmd takes a TMD atom's normal from neighbours of the same molecule AND
    the same atom type (LAMMPS ``pair_ilp_tmd.cpp``: ``imol == jmol && type[i]
    == type[j]``), so a chalcogen labelled once by its many-body potential
    (``Mo S``) would put both sub-layers in one neighbour set and LAMMPS stops
    with "too many neighbors for TMD atoms". Empty unless the style resolves
    to ilp/tmd; a chalcogen the potential already splits (``S1 S2``) is left
    alone, as is a material without a metal plane to split around.
    """
    elems = set(elements)
    if style != 'ilp' or ilp_substyle(elems) != 'ilp/tmd' or not elems - CHALCOGENS:
        return set()
    return {el for el in elems & CHALCOGENS if int(pot_counts.get(el, 1)) == 1}


def resolve_interlayer_file(name: str, style: str,
                            base_dir: Optional[Path]) -> Path:
    """Find an interlayer parameter file like any other potential.

    Looks relative to ``base_dir``/working directory first, then in the bundled
    ``examples/potentials/<ilp|kc>/``.

    Raises:
        FileNotFoundError: Naming both places searched.
    """
    try:
        return get_potential_path(name, base_dir)
    except FileNotFoundError:
        pass
    bundled_dir = EXAMPLES_POTENTIALS_DIR / ('ilp' if style == 'ilp' else 'kc')
    bundled = bundled_dir / Path(name).name
    if bundled.exists():
        return bundled
    searched = base_dir if base_dir is not None else Path.cwd()
    raise FileNotFoundError(
        f"Interlayer file '{name}' not found in {searched} (working directory / "
        f"config directory) or in the bundled {bundled_dir}.")


def _sheet_elements(sheets, base_dir: Optional[Path]) -> Optional[Set[str]]:
    """Union of the CIF elements of ``sheets``; None if a CIF cannot be read."""
    # Deferred: core.utils.structures reaches ase (tests/repo/test_import_weight.py).
    from ..core.utils.structures import cifread  # pylint: disable=import-outside-toplevel
    found: Set[str] = set()
    for sheet in sheets:
        try:
            path = Path(sheet.cif_path)
            if not path.exists():
                path = get_material_path(sheet.cif_path, base_dir)
            found |= set(cifread(path)['elements'])
        except Exception:  # pylint: disable=broad-exception-caught
            return None
    return found


def check_interlayer_choice(config: Any, base_dir: Optional[Path] = None) -> None:
    """Reject interlayer settings that cannot produce a valid run.

    Raises:
        ValueError: On a non-``lj`` style combined with ``constraint_mode``,
            an internal-LJ potential, a missing Gaussian ``g`` or a missing
            parameter file that cannot be defaulted.
    """
    # Deferred: potentials.utils reaches ase (tests/repo/test_import_weight.py).
    # pylint: disable=import-outside-toplevel
    from .utils import POTENTIALS_WITH_INTERNAL_LJ
    general = config.general
    style = general.interlayer_style
    if style == 'lj':
        return

    mode = config.settings.simulation.constraint_mode
    if mode != 'none':
        raise ValueError(
            f"interlayer_style '{style}' is incompatible with constraint_mode "
            f"'{mode}': the many-body/Gaussian layers need the f_fsbot reaction "
            "force, not the atom_bonds/com_spring constraint. Set "
            "constraint_mode = none or interlayer_style = lj.")

    sheets = list(config.sheets) or [config.sheet]
    sheets = sheets + list(config.flake_sheets)
    for sheet in sheets:
        if sheet.pot_type in POTENTIALS_WITH_INTERNAL_LJ:
            raise ValueError(
                f"interlayer_style '{style}' cannot be combined with pot_type "
                f"'{sheet.pot_type}' ({sheet.mat}): it carries its own interlayer "
                "term, so the choice would be a silent no-op.")

    if style == 'lj_g':
        missing = [s.mat for s in sheets
                   if gaussian_g(s.mat, s.interlayer_g) is None]
        if missing:
            raise ValueError(
                f"interlayer_style 'lj_g' needs a Gaussian strength g (meV) for "
                f"{sorted(set(missing))}: set interlayer_g in the sheet section "
                f"(built in: {sorted(GAUSSIAN_G_MEV)}).")
        return

    file = general.interlayer_file
    if file is not None:
        name = Path(str(file)).name
        ok = name.endswith('.ILP') if style == 'ilp' else '.KC' in name
        if not ok:
            raise ValueError(
                f"interlayer_file '{file}' does not match interlayer_style "
                f"'{style}' (ilp needs a *.ILP file, kc a *.KC / *.KC-full / "
                "*_taper.KC file). One interlayer_file serves a whole style "
                "sweep, so sweep styles that need different files as "
                "separate configs.")
    if general.interlayer_file is None:
        elements = _sheet_elements(sheets, base_dir)
        if elements is not None and default_interlayer_file(style, elements) is None:
            raise ValueError(
                f"interlayer_style '{style}' has no bundled parameter file for "
                f"elements {sorted(elements)}: set general interlayer_file.")
