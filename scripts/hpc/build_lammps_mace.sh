#!/usr/bin/env bash
# Build a MACE-enabled LAMMPS driven by wcwitt/symmetrix (`pair_style
# symmetrix/mace`), with Kokkos and EXTRA-PAIR (`dispersion/d3`).
#
# Usage: PREFIX=$HOME/opt TARGET=workstation GPU_ARCH=AMPERE86 ./build_lammps_mace.sh
#   TARGET  : workstation | cx3 | hx1   (selects the module preamble)
#   GPU_ARCH: Kokkos arch of the card -- AMPERE86 (RTX30xx), ADA89 (L40S),
#             AMPERE80 (A100). GPU=0 builds the CPU/OpenMP variant instead.
#   CONDA_ENV: prefix supplying mpicxx/mpicc + OpenBLAS. Empty => use modules.
#
# Idempotent: each stage is guarded, so a re-run after a failure resumes.
#
# WHY symmetrix AND NOT THE ACEsuit FORK
# -------------------------------------
# This script used to build `ACEsuit/lammps --branch mace`, which provides
# `pair_style mace`. FrictionSim2D does not emit that style. `src/core/mlip.py`
# sets MACE's `style_name = 'symmetrix/mace'` because symmetrix is the
# implementation ML-MIX supports for hybrid ML/MM (`mliappy mace` is listed
# INCOMPATIBLE), so a deck generated by this package cannot run on an ACEsuit
# build at all. It also needs no libtorch: symmetrix reads a plain `.json`.
#
# THE MODEL IS NOT WHAT YOU DOWNLOAD
# ----------------------------------
# symmetrix does not read a MACE `.model`/`.model-lammps.pt` checkpoint. Extract
# a `.json` for the exact element set of your cell, on a machine with
# `mace-torch` + the symmetrix python package (stage `model`, below):
#
#   symmetrix_extract_mace -m mace-mpa-0-medium.model --chemical-symbols Mo S
#
# The element list is BAKED IN, so a `.json` is specific to that element set --
# unlike a DeePMD `.pth`, which carries the whole periodic table. A different
# material needs a different extraction.
#
# THE MANDATORY PATCH
# -------------------
# symmetrix has a heap overflow that makes MACE SILENTLY WRONG on CUDA:
# `mace_types` is allocated with one slot per MODEL ELEMENT but filled with one
# per LAMMPS ATOM TYPE. Those agree only when ntypes == n_elements, which holds
# for upstream's examples and fails for any multi-layer cell (an h-MoS2 trilayer
# has 7 types against a 2-element model). On CUDA the device then reads
# out-of-bounds and returns -126.5489 eV instead of -173.40779 eV WITH NO ERROR;
# the corrupted heap also kills `hybrid/overlay ... dispersion/d3`. Not upstream
# as of origin/main 0d86e1e. This script applies
# `symmetrix-mace_types-overflow.patch` and REFUSES TO BUILD WITHOUT IT.
# Always confirm -173.40779 eV on the reference 24-atom h-MoS2 bilayer before
# trusting any number from this binary.
set -euo pipefail

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
PREFIX="${PREFIX:-$HOME/opt}"
TARGET="${TARGET:-workstation}"
GPU="${GPU:-1}"
GPU_ARCH="${GPU_ARCH:-AMPERE86}"
STAGE="${STAGE:-all}"            # fetch | build | model | all
NJOBS="${NJOBS:-${NCPUS:-$(nproc)}}"
CONDA_ENV="${CONDA_ENV:-}"
SRC="${SRC:-$PREFIX/lammps-mace}"
SYM="${SYM:-$PREFIX/symmetrix}"
BUILD="${BUILD:-build-$([ "$GPU" = 1 ] && echo gpu || echo omp)}"
# symmetrix requires a LAMMPS >= 10 Sep 2025 (that is when the release it
# patches against landed); deepmd-kit is ABI-locked to 29 Aug 2024, which is
# why MACE and DeePMD are two mutually incompatible builds and two source trees.
LAMMPS_BRANCH="${LAMMPS_BRANCH:-patch_10Sep2025}"

# --- 1. environment --------------------------------------------------------
# NEVER `module purge` on cx3: it drops the /sw-eb MODULEPATH, GCC and CMake
# become unloadable, and the build silently falls back to g++ 8 (no C++20) with
# no cmake at all -> rc=127. Load additively and warn rather than dying, so a
# site with different module names can still get through.
MODS=""
load_modules() {
  for m in "$@"; do
    if module load "$m" 2>/dev/null; then MODS="$MODS $m"
    else echo "WARN: cannot load module $m" >&2; fi
  done
  MODS="${MODS# }"
}
case "$TARGET" in
  cx3) load_modules tools/prod "${GCC_MODULE:-GCC/13.3.0}" \
                    "${CMAKE_MODULE:-CMake/3.29.3-GCCcore-13.3.0}" \
                    "${CUDA_MODULE:-CUDA/12.6.0}" ;;
  hx1) load_modules "${GCC_MODULE:-GCC/13.3.0}" "${CMAKE_MODULE:-CMake/3.29.3}" \
                    "${CUDA_MODULE:-CUDA/12.6.0}" ;;
  workstation) : ;;   # system gcc >= 10, cmake >= 3.20, CUDA toolkit on PATH
  *) echo "ERROR: unknown TARGET '$TARGET' (expected workstation|cx3|hx1)" >&2; exit 2 ;;
esac
[ -n "$CONDA_ENV" ] && export PATH="$CONDA_ENV/bin:$PATH"

die() { echo "FATAL: $*" >&2; echo "       modules loaded: ${MODS:-<none>}" >&2; exit 1; }

# CUDA must come from the MODULE, not from conda: a conda `nvcc` can shadow it
# and lack the headers nvcc_wrapper needs, giving a baffling
# "fatal error: cuda_runtime.h: No such file or directory" mid-configure.
if [ "$GPU" = 1 ]; then
  CUDA_HOME="${CUDA_HOME:-${EBROOTCUDA:-}}"
  [ -n "$CUDA_HOME" ] || CUDA_HOME=$(dirname "$(dirname "$(command -v nvcc 2>/dev/null || echo /x/x)")")
  export CUDA_HOME PATH="$CUDA_HOME/bin:$PATH"
fi

mkdir -p "$PREFIX"

# --- 2. sources ------------------------------------------------------------
# Split out as its own stage because clones need outbound network, which
# compute nodes usually lack, while the compile is far too heavy for a login
# node (~959 objects, 30-90 min of nvcc). Fetch on the login node, build in a job.
do_fetch() {
  [ -d "$SRC" ] || git clone --depth 1 --branch "$LAMMPS_BRANCH" \
    https://github.com/lammps/lammps.git "$SRC"
  [ -d "$SYM" ] || git clone --recursive https://github.com/wcwitt/symmetrix.git "$SYM"

  # --- patch symmetrix (MANDATORY -- see header) ---------------------------
  local kk="$SYM/pair_symmetrix/pair_symmetrix_mace_kokkos.cpp"
  grep -q 'LOCAL BUGFIX' "$kk" || \
    ( cd "$SYM" && git apply "$HERE/symmetrix-mace_types-overflow.patch" )
  grep -q 'LOCAL BUGFIX' "$kk" || \
    die "symmetrix patch did not apply -- refusing to build a silently-wrong CUDA binary"

  # -march=native / -ffast-math clash with nvcc; strip them (no-op if absent).
  sed -i 's/\$<\$<COMPILE_LANGUAGE:CXX>:-march=native>//; s/\$<\$<COMPILE_LANGUAGE:CXX>:-ffast-math>//' \
    "$SYM/libsymmetrix/CMakeLists.txt"

  # --- wire symmetrix into LAMMPS ------------------------------------------
  # symmetrix is NOT a plugin: install.sh symlinks pair_symmetrix_mace* into
  # lammps/src{,/KOKKOS} and appends to lammps/cmake/CMakeLists.txt, so it is
  # COMPILED INTO the binary. (That is why a conda-forge LAMMPS can never gain
  # this pair style, and why the DeePMD build -- which loads dpplugin.so at run
  # time -- cannot be reused.) install.sh bakes ABSOLUTE paths and symlinks, so
  # a tree wired elsewhere dangles after an rsync: always strip and redo.
  sed -i '/libsymmetrix/d; /target_link_libraries(lammps PRIVATE symmetrix)/d; /install(TARGETS symmetrix EXPORT LAMMPS_Targets)/d' \
    "$SRC/cmake/CMakeLists.txt"
  rm -f "$SRC/src/pair_symmetrix_mace."{cpp,h} \
        "$SRC/src/KOKKOS/pair_symmetrix_mace_kokkos."{cpp,h}
  ( cd "$SYM/pair_symmetrix" && ./install.sh "$SRC" )
  echo "OK: sources fetched, patched and wired at $SRC"
}

# --- 3. build --------------------------------------------------------------
do_build() {
  [ -d "$SRC" ] && [ -d "$SYM" ] || die "sources missing -- run STAGE=fetch first"
  grep -q 'LOCAL BUGFIX' "$SYM/pair_symmetrix/pair_symmetrix_mace_kokkos.cpp" || \
    die "symmetrix is unpatched -- run STAGE=fetch"
  command -v cmake >/dev/null || die "no cmake on PATH"
  local gxx; gxx=$(g++ -dumpversion | cut -d. -f1)
  [ "$gxx" -ge 10 ] || die "g++ $gxx cannot compile C++20 -- the GCC module did not load"

  local args=(
    -D CMAKE_BUILD_TYPE=Release
    -D CMAKE_CXX_STANDARD=20 -D CMAKE_CXX_STANDARD_REQUIRED=ON
    -D BUILD_SHARED_LIBS=ON -D BUILD_OMP=ON
    -D CMAKE_INSTALL_LIBDIR=lib
    -D PKG_KOKKOS=ON -D Kokkos_ENABLE_SERIAL=ON -D Kokkos_ENABLE_OPENMP=ON
    -D SYMMETRIX_KOKKOS=ON
    # EXTRA-PAIR carries `dispersion/d3`, the only supported vdW lever for an
    # MLIP cell. MANYBODY/MOLECULE/RIGID/KSPACE keep classical decks buildable
    # with the same binary.
    -D PKG_MANYBODY=ON -D PKG_MOLECULE=ON -D PKG_RIGID=ON
    -D PKG_KSPACE=ON -D FFT=KISS -D PKG_EXTRA-FIX=ON -D PKG_EXTRA-PAIR=ON
  )
  if [ "$GPU" = 1 ]; then
    command -v nvcc >/dev/null || die "no nvcc on PATH -- load a CUDA module (or set GPU=0)"
    [ -e "$CUDA_HOME/include/cuda_runtime.h" ] || \
      die "no cuda_runtime.h under CUDA_HOME=$CUDA_HOME (conda nvcc without headers?)"
    args+=(-D CMAKE_CXX_COMPILER="$SRC/lib/kokkos/bin/nvcc_wrapper" -D CMAKE_CXX_FLAGS=""
           -D Kokkos_ENABLE_CUDA=ON -D "Kokkos_ARCH_${GPU_ARCH}=ON"
           -D SYMMETRIX_SPHERICART_CUDA=OFF)
  fi
  if [ -n "$CONDA_ENV" ]; then
    [ -x "$CONDA_ENV/bin/mpicxx" ] || die "no mpicxx in $CONDA_ENV"
    [ -e "$CONDA_ENV/lib/libopenblas.so.0" ] || die "no libopenblas.so.0 in $CONDA_ENV"
    args+=(-D BUILD_MPI=ON
           -D MPI_CXX_COMPILER="$CONDA_ENV/bin/mpicxx" -D MPI_C_COMPILER="$CONDA_ENV/bin/mpicc"
           -D BLAS_LIBRARIES="$CONDA_ENV/lib/libopenblas.so.0"
           -D LAPACK_LIBRARIES="$CONDA_ENV/lib/libopenblas.so.0")
  else
    args+=(-D BUILD_MPI="${BUILD_MPI:-OFF}")
  fi

  cd "$SRC"
  cmake -B "$BUILD" "${args[@]}" cmake
  cmake --build "$BUILD" -j"$NJOBS"
  [ -x "$SRC/$BUILD/lmp" ] || die "build produced no lmp"
  echo "OK: $SRC/$BUILD/lmp"
  # Deliberately NOT run here: on a GPU build `lmp` links libcuda.so.1, the
  # NVIDIA *driver* library, which exists only on GPU nodes. Verify on one:
  echo "VERIFY on a GPU node before trusting any number:"
  echo "  $SRC/$BUILD/lmp -in <reference 24-atom h-MoS2 bilayer>   # must give -173.40779 eV"
}

# --- 4. model conversion (optional, needs python) --------------------------
# Only needed to PRODUCE a .json. The cluster that runs LAMMPS needs neither
# mace-torch nor python -- symmetrix reads the .json directly.
do_model() {
  if [ ! -d "$PREFIX/mace-venv" ]; then
    "${PYTHON_BIN:-python3}" -m venv "$PREFIX/mace-venv"
    "$PREFIX/mace-venv/bin/pip" install --upgrade pip
    "$PREFIX/mace-venv/bin/pip" install mace-torch
    "$PREFIX/mace-venv/bin/pip" install "$SYM"
  fi
  echo "OK: $PREFIX/mace-venv"
  echo "Extract a model for YOUR element set (the list is baked into the .json):"
  echo "  source $PREFIX/mace-venv/bin/activate"
  echo "  symmetrix_extract_mace -m mace-mpa-0-medium.model --chemical-symbols Mo S"
}

case "$STAGE" in
  fetch) do_fetch ;;
  build) do_build ;;
  model) do_model ;;
  all)   do_fetch; do_build ;;
  *) echo "ERROR: unknown STAGE '$STAGE' (expected fetch|build|model|all)" >&2; exit 2 ;;
esac
